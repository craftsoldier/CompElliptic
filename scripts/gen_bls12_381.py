"""
Generate `CompElliptic/Fields/BLS12_381.lean`: the BLS12-381 scalar prime field `r_𝕊`, the base
field of the Jubjub curve, with a Lucas/Pratt primality certificate and a Tonelli–Shanks instance.
The certificate machinery (factorization and primitive-root search via PARI/GP, recursive
certificate emission) is in `pratt.py`.

The BLS12-381 base field, curve, and pairing are not defined here.

Usage: run from the project root and write the result to the field file:

    python3 scripts/gen_bls12_381.py > CompElliptic/Fields/BLS12_381.lean
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pratt import field_block

# BLS12-381 scalar field order r_𝕊; Zcash protocol spec §5.4.9.2, see also
# https://github.com/zkcrypto/bls12_381.
R_S = 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001

# r_𝕊 - 1 = 2^S · T with T odd.
S = 32
T = (R_S - 1) >> S
assert T % 2 == 1 and (T << S) + 1 == R_S

# G is a quadratic non-residue, so G^T is a primitive 2^S-th root of unity.
G = 7
assert pow(G, (R_S - 1) // 2, R_S) == R_S - 1
ROOT = pow(G, T, R_S)

HEADER = f"""\
/-
Copyright (c) 2026 CompElliptic Contributors.
Released under the Apache License, Version 2.0, or the MIT license, at your option,
as described in the files LICENSE-APACHE and LICENSE-MIT.
Authors: Julian Abraham
-/
import CompPoly.Fields.PrattCertificate
import CompElliptic.Fields.Sqrt
import Mathlib.NumberTheory.LegendreSymbol.Basic

/-!
# The BLS12-381 scalar prime field

`BLS12_381_SCALAR_CARD` is `r_𝕊`, the order of the scalar field of BLS12-381 and the base field
of the Jubjub curve (Zcash Protocol Specification
[§5.4.9.2 "BLS12-381 pairing"](https://zips.z.cash/protocol/protocol.pdf#blspairing)). We give
`r_𝕊` a Lucas/Pratt primality certificate, following the pattern of `CompElliptic.Fields.Pasta`;
the certificate was generated by `scripts/gen_bls12_381.py` from the factorization of `r_𝕊 - 1`
(PARI/GP). The BLS12-381 base field, curve, and pairing are not defined here.

The Tonelli–Shanks instance `bls12_381Scalar` has root of unity `{G}ᵀ`. Its order is checked by the
kernel rather than by `native_decide`, from Euler's criterion (`{G}` is a non-residue,
`seven_not_isSquare`) and Fermat's little theorem.
-/

namespace CompElliptic.Fields.BLS12_381
"""

FOOTER = f"""
/-- `{G}` is nonzero in the BLS12-381 scalar field. -/
theorem seven_ne_zero : ({G} : BLS12381ScalarField) ≠ 0 := by decide

/-- `{G}` is a non-residue in the BLS12-381 scalar field, by Euler's criterion. -/
theorem seven_not_isSquare : ¬ IsSquare ({G} : BLS12381ScalarField) := by
  rw [ZMod.euler_criterion BLS12_381_SCALAR_CARD seven_ne_zero]
  reduce_mod_char
  decide

/-- `{G}ᵀ = 0x{ROOT:x}`,
where `T = (r_𝕊 - 1)/2^{S}`. Stated over `ZMod`, because `reduce_mod_char` keys on the `ZMod`
spelling of the type, which the `BLS12381ScalarField` abbrev hides. -/
theorem seven_pow_oddPart :
    ({G} : ZMod BLS12_381_SCALAR_CARD) ^ ((BLS12_381_SCALAR_CARD - 1) / 2 ^ {S}) =
      0x{ROOT:x} := by
  reduce_mod_char

/-- Tonelli–Shanks data for the BLS12-381 scalar field `𝔽_{{r_𝕊}}`: `r_𝕊 - 1 = 2^{S} · T`, with
`rootOfUnity = {G}ᵀ` (`seven_pow_oddPart`). -/
def bls12_381Scalar : TonelliShanks BLS12381ScalarField where
  twoAdicity := {S}
  oddPart := 0x{T:x}
  rootOfUnity := 0x{ROOT:x}
  valid := {{
    rootOfUnity_order := by
      haveI : Fact (Nat.Prime 2) := ⟨Nat.prime_two⟩
      rw [← seven_pow_oddPart]
      refine orderOf_eq_prime_pow (p := 2) ?_ ?_
      · rw [← pow_mul, show (BLS12_381_SCALAR_CARD - 1) / 2 ^ {S} * 2 ^ {S - 1} =
          BLS12_381_SCALAR_CARD / 2 by decide]
        exact fun h => seven_not_isSquare ((ZMod.euler_criterion _ seven_ne_zero).mpr h)
      · rw [← pow_mul, show (BLS12_381_SCALAR_CARD - 1) / 2 ^ {S} * 2 ^ ({S - 1} + 1) =
          BLS12_381_SCALAR_CARD - 1 by decide]
        exact ZMod.pow_card_sub_one_eq_one seven_ne_zero }}

-- `√4` squares back to `4`; `√{G} = none` ({G} is a non-residue, cf. `seven_not_isSquare`).
example : (bls12_381Scalar.sqrt? 4).map (· ^ 2) = some 4 := by native_decide
example : bls12_381Scalar.sqrt? {G} = none := by native_decide

end CompElliptic.Fields.BLS12_381
"""


if __name__ == "__main__":
    out = HEADER
    out += field_block("BLS12_381_SCALAR", R_S, "BLS12381ScalarField",
                       "The order `r_𝕊` of the BLS12-381 scalar field.",
                       "The BLS12-381 scalar field `𝔽_{r_𝕊}`, the base field of the Jubjub curve.",
                       "`r_𝕊` is prime, by a Pratt certificate.")
    out += FOOTER
    print(out, end="")
